// Menu aktif? Board ("/") hanya cocok persis; halaman lain juga aktif di
// sub-halamannya (mis. /leads/123 tidak menyalakan Board).
export function isNavActive(pathname: string, href: string): boolean {
  return href === "/" ? pathname === "/" : pathname.startsWith(href);
}
